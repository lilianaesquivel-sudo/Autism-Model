clear; clc; close all;

%% 1. Parámetros por índice k

Lk = @(t,k) ...
    (k == 1).*0.8 + ...
    (k == 2).*0.1 + ...
    (k == 5).*0.6;

Hk = @(t,k) ...
    (k == 1).*0.2 + ...
    (k == 2).*0.8 + ...
    (k == 5).*0.1;

Zk = @(t,k) ...
    (k == 1).*0.8 + ...
    (k == 2).*0.2 + ...
    (k == 5).*0.9;

% Parametros del modelo (ejemplos: reemplazar por los reales)
alpha_H = 2.5;
alpha_Z = 10;
eta = 2.5;
Z_bar = 0.14;
beta = 5;
R_bar = 1;
A_b = 0.5;

mu = 0.05;
nu_H = 0.2;
nu_A = 16;
A_d = 0.65;

lambda = 0.2;
delta = 0.3;



function [s_kj,pH_kj,pZ_kj,sigma,I_k] = config(t_0,t_1,t_2,t_3,tt_0,tt_1,I);
%% 3. Función s_k(t)
r = 0.5;
s_kj = @(t,k) ...
    (k == 5 & t >= t_0 & t < t_1).*0.3 + ...
    (k == 5 & t >= t_2 & t <= t_3).*0.7 + ...
    (k == 2 & t >= t_0 & t < t_1).*0.8 + ...
    (k == 2 & t >= t_2 & t <= t_3).*0.4 + ...
    (k == 1 & t >= t_0 & t < t_1).*0.5;
%% 4. Parámetros adicionales
pH_kj = @(t,k) ...
    (k == 5 & t >= t_0 & t < t_1).*0.75 + ...
    (k == 5 & t >= t_2 & t <= t_3).*0.375 + ...
    (k == 2 & t >= t_0 & t < t_1).*0.75 + ...
    (k == 2 & t >= t_2 & t <= t_3).*0.50 + ...
    (k == 1 & t >= t_0 & t < t_1).*0.125;
pZ_kj = @(t,k) ...
    (k == 5 & t >= t_0 & t < t_1).*0 + ...
    (k == 5 & t >= t_2 & t <= t_3).*0.75 + ...
    (k == 2 & t >= t_0 & t < t_1).*0 + ...
    (k == 2 & t >= t_2 & t <= t_3).*0.50 + ...
    (k == 1 & t >= t_0 & t < t_1).*1;
%% 7. Función sigma(t,k)

sigma = @(t,k) ...
    (k == 5 & t >= t_0 & t < t_1).*0.5 + ...
    (k == 5 & t >= t_2 & t <= t_3).*(-0.5) + ...
    (k == 2 & t >= t_0 & t < t_1).*1 + ...
    (k == 2 & t >= t_2 & t <= t_3).*0.5 + ...
    (k == 1 & t >= t_0 & t < t_1).*0.5;
% PENDIENTE: definir la fórmula matemática de EI_k(t,k).
I_k = @(t,k) (t >= tt_0 & t <= tt_1) .* I;
end



t_0 = 0.5;
t_1 = 1;
t_2 = 3;
t_3 = 4;
tt_0 = 5;
tt_1 = 6;
I = 0.5;

[s_kj,pH_kj,pZ_kj,sigma,I_k] = config(t_0,t_1,t_2,t_3,tt_0,tt_1,I);


%% 5. Función r_k(t)
r = 0.5;
r_kj = @(t,k) ...
    1 - r*Lk(t,k)*(1 - s_kj(t,k));


h0 = 0.2;
HH_k = @(t,k) ...
    h0 + (1 - h0)*Hk(t,k);

EH_kj = @(t,k) ...
    pH_kj(t,k)*r_kj(t,k)*HH_k(t,k)*s_kj(t,k);

EZ_kj = @(t,k) ...
    pZ_kj(t,k)*Zk(t,k)*s_kj(t,k);

EI_k = @(t,k) ...
    pH_kj(t,k)*r_kj(t,k)*HH_k(t,k)*I_k(t,k);


%% 9. Funciones S_H y S_Z
% Requieren que EI_k esté definido.
SH_k = @(t,k) ...
    (1 - EI_k(t,k))*(1 - EH_kj(t,k));
SZ_k = @(t,k) ...
    (1 - EI_k(t,k))*(1 - EZ_kj(t,k));

%% 10. Función D(t)

D = @(t) ...
    EZ_kj(t,1) + ...
    EZ_kj(t,2) + ...
    EZ_kj(t,3) + ...
    EZ_kj(t,4) + ...
    EZ_kj(t,5) + ...
    EI_k(t,1) + ...
    EI_k(t,2) + ...
    EI_k(t,3) + ...
    EI_k(t,4) + ...
    EI_k(t,5);

w = @(j,t) ...
    (j == 1 & D(t) > 0).* ( ...
    EZ_kj(t,1)*sigma(t,1) + ...
    EZ_kj(t,2)*sigma(t,2) + ...
    EZ_kj(t,3)*sigma(t,3) + ...
    EZ_kj(t,4)*sigma(t,4) + ...
    EZ_kj(t,5)*sigma(t,5) + ...
    EI_k(t,1)*sigma(t,1) + ...
    EI_k(t,2)*sigma(t,2) + ...
    EI_k(t,3)*sigma(t,3) + ...
    EI_k(t,4)*sigma(t,4) + ...
    EI_k(t,5)*sigma(t,5) ) ./ (D(t) + (D(t) == 0)) ...
    - (j == 2 & D(t) > 0).* ( ...
    EZ_kj(t,1)*sigma(t,1) + ...
    EZ_kj(t,2)*sigma(t,2) + ...
    EZ_kj(t,3)*sigma(t,3) + ...
    EZ_kj(t,4)*sigma(t,4) + ...
    EZ_kj(t,5)*sigma(t,5) + ...
    EI_k(t,1)*sigma(t,1) + ...
    EI_k(t,2)*sigma(t,2) + ...
    EI_k(t,3)*sigma(t,3) + ...
    EI_k(t,4)*sigma(t,4) + ...
    EI_k(t,5)*sigma(t,5) ) ./ (D(t) + (D(t) == 0));

% Funciones temporales
S_H = @(t) 1-SH_k(t,1)*SH_k(t,2)*SH_k(t,3)*SH_k(t,4)*SH_k(t,5);
S_Z = @(t) 1-SZ_k(t,1)*SZ_k(t,2)*SZ_k(t,3)*SZ_k(t,4)*SZ_k(t,5);


% Perfil gaussiano
A_star = 0.5;
sigma = 0.15;
C = 1;

Gamma = @(A) C .* exp(-((A-A_star).^2) ./ (sigma^2));
% T_Z = @(t) A_star + w(1,t)*(1-A_star) - w(2,t)*A_star;
T_Z = @(t) (D(t) > 0) .* (A_star + w(1,t)*(1-A_star) - w(2,t)*A_star) ...
    + (D(t) == 0) .* A_star;


% Condiciones iniciales: [A(0); R(0); P(0)]
u0 = [1; 0.5; 0];

% Resolver sistema
[t,u] = sistema_edo(u0, S_H, S_Z, T_Z, Gamma, ...
    A_star, alpha_H, alpha_Z, eta, Z_bar, beta, R_bar, ...
    A_b, mu, nu_H, nu_A, A_d, lambda, delta);

% Graficar
figure;
plot(t,u,'LineWidth',1.5);
legend('A(t)','R(t)','P(t)','Location','best');
xlabel('Tiempo t');
ylabel('Soluciones');
title('Children B');
grid on;
exportgraphics(gcf, 'childrenB.png', 'Resolution', 300);

function [t,u] = sistema_edo(u0, S_H, S_Z, T_Z, Gamma, ...
    A_star, alpha_H, alpha_Z, eta, Z_bar, beta, R_bar, ...
    A_b, mu, nu_H, nu_A, A_d, lambda, delta)

t0 = 0;
tf = 100;
N = 10000;
h = (tf-t0)/N;

f = @(t,u) [
    alpha_H*S_H(t)*(1-u(1)) ...
    + alpha_Z*S_Z(t)*(T_Z(t)-u(1)) ...
    + eta*Z_bar*(1-Gamma(u(1)))*(A_star-u(1)) ...
    + beta*R_bar*(A_b-u(1));

    mu*(1-u(2)) ...
    - nu_H*S_H(t)*u(2) ...
    - nu_A*max(u(1)-A_d, 0)*u(2);

    lambda*u(2)*Gamma(u(1))*(1-u(3)) ...
    - delta*(1-Gamma(u(1)))*u(3)
    ];

t = linspace(t0,tf,N+1)';
u = zeros(N+1,length(u0));
u(1,:) = u0(:)';

% Euler explicito
for n = 1:N
    u_actual = u(n,:)';
    u_siguiente = u_actual + h*f(t(n),u_actual);
    u(n+1,:) = u_siguiente';
end

end
